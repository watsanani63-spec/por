-- หากเคยสร้างตาราง/นโยบายชื่อเดียวกันแล้ว ให้ตรวจสอบก่อนรันซ้ำ

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  phone text not null default '',
  role text not null default 'user' check (role in ('user', 'admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.registrations (
  id bigint generated by default as identity primary key,
  user_id uuid not null unique references public.profiles(id) on delete cascade,
  application_no text unique,
  prefix text not null default '',
  first_name text not null,
  last_name text not null,
  birth_date date,
  gender text,
  phone text not null,
  email text not null,
  previous_school text,
  education_level text,
  department text not null,
  academic_year text not null default '2569',
  address_no text,
  village text,
  subdistrict text,
  district text,
  province text,
  postal_code text,
  guardian_name text,
  guardian_phone text,
  status text not null default 'pending'
    check (status in ('pending', 'approved', 'rejected')),
  admin_note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- เชื่อม relation โดยตรงเพื่อให้ select registrations(...profiles...) ได้
-- user_id อ้าง profiles.id อยู่แล้ว

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists registrations_updated_at on public.registrations;
create trigger registrations_updated_at
before update on public.registrations
for each row execute function public.set_updated_at();

create or replace function public.create_profile_for_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name, phone, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name', ''),
    coalesce(new.raw_user_meta_data ->> 'phone', ''),
    'user'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_profile on auth.users;
create trigger on_auth_user_created_profile
after insert on auth.users
for each row execute procedure public.create_profile_for_new_user();

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and role = 'admin'
  );
$$;

alter table public.profiles enable row level security;
alter table public.registrations enable row level security;

drop policy if exists "profile_select_own_or_admin" on public.profiles;
create policy "profile_select_own_or_admin"
on public.profiles for select to authenticated
using (id = (select auth.uid()) or public.is_admin());

drop policy if exists "profile_insert_self" on public.profiles;
create policy "profile_insert_self"
on public.profiles for insert to authenticated
with check (id = (select auth.uid()) and role = 'user');

drop policy if exists "profile_update_self" on public.profiles;
create policy "profile_update_self"
on public.profiles for update to authenticated
using (id = (select auth.uid()))
with check (id = (select auth.uid()) and role = 'user');

drop policy if exists "registrations_select_owner_admin" on public.registrations;
create policy "registrations_select_owner_admin"
on public.registrations for select to authenticated
using (user_id = (select auth.uid()) or public.is_admin());

drop policy if exists "registrations_insert_owner" on public.registrations;
create policy "registrations_insert_owner"
on public.registrations for insert to authenticated
with check (
  user_id = (select auth.uid())
  and status = 'pending'
);

drop policy if exists "registrations_update_owner_pending" on public.registrations;
create policy "registrations_update_owner_pending"
on public.registrations for update to authenticated
using (user_id = (select auth.uid()) and status = 'pending')
with check (user_id = (select auth.uid()) and status = 'pending');

drop policy if exists "registrations_admin_update" on public.registrations;
create policy "registrations_admin_update"
on public.registrations for update to authenticated
using (public.is_admin())
with check (public.is_admin());

drop policy if exists "registrations_admin_delete" on public.registrations;
create policy "registrations_admin_delete"
on public.registrations for delete to authenticated
using (public.is_admin());

